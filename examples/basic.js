/**
 * Ejemplo básico de DOCUGEN-LIB
 * Muestra cómo usar la librería para generar un PDF simple
 *
 * Ejecutar: node examples/basic.js
 */

import fs from 'node:fs/promises';
import { DocugenEngine } from '../src/index.js';

async function main() {
  console.log('🚀 DOCUGEN-LIB - Ejemplo Básico\n');

  // Crear instancia del motor
  const docugen = new DocugenEngine();

  // Definir una plantilla simple (en la práctica, esto vendría de un JSON)
  const invoiceTemplate = {
    name: 'Invoice Template',
    description: 'Simple invoice template with dynamic data',
    dimensions: {
      width: 794,
      height: 1123,
      unit: 'px',
    },
    page: {
      backgroundColor: '#ffffff',
      margin: { top: 40, right: 40, bottom: 40, left: 40 },
    },
    elements: [
      {
        id: 'title',
        type: 'title',
        x: 40,
        y: 40,
        width: 700,
        height: 40,
        text: 'INVOICE',
        fontSize: 32,
        color: '#000000',
        align: 'center',
      },
      {
        id: 'invoice_number',
        type: 'text',
        x: 40,
        y: 100,
        width: 300,
        height: 20,
        text: 'Invoice #{{invoice_number}}',
        fontSize: 12,
        color: '#333333',
      },
      {
        id: 'date',
        type: 'text',
        x: 40,
        y: 130,
        width: 300,
        height: 20,
        text: 'Date: {{invoice_date}}',
        fontSize: 12,
        color: '#333333',
      },
      {
        id: 'client_section_title',
        type: 'subtitle',
        x: 40,
        y: 180,
        width: 300,
        height: 25,
        text: 'Bill To',
        fontSize: 14,
        color: '#000000',
      },
      {
        id: 'client_name',
        type: 'paragraph',
        x: 40,
        y: 215,
        width: 300,
        height: 40,
        text: '{{client_name}}',
        fontSize: 12,
        color: '#333333',
      },
      {
        id: 'client_email',
        type: 'text',
        x: 40,
        y: 260,
        width: 300,
        height: 20,
        text: '{{client_email}}',
        fontSize: 11,
        color: '#666666',
      },
      {
        id: 'items_title',
        type: 'subtitle',
        x: 40,
        y: 320,
        width: 300,
        height: 25,
        text: 'Items',
        fontSize: 14,
        color: '#000000',
      },
      {
        id: 'items_table',
        type: 'table',
        x: 40,
        y: 360,
        width: 714,
        height: 200,
        text: 'Description | Quantity | Price\n{{items_description}} | {{items_quantity}} | ${{items_price}}',
        fontSize: 11,
        color: '#333333',
        stroke: '#cccccc',
      },
      {
        id: 'total_label',
        type: 'text',
        x: 550,
        y: 580,
        width: 150,
        height: 25,
        text: 'Total Amount:',
        fontSize: 13,
        color: '#000000',
        align: 'right',
      },
      {
        id: 'total_amount',
        type: 'title',
        x: 550,
        y: 610,
        width: 150,
        height: 30,
        text: '${{total_amount}}',
        fontSize: 18,
        color: '#2ecc71',
        align: 'right',
      },
      {
        id: 'footer',
        type: 'footer',
        x: 40,
        y: 1050,
        width: 714,
        height: 20,
        text: 'Generated by Docugen-Lib © 2026',
        fontSize: 10,
        color: '#999999',
        align: 'center',
      },
    ],
    metadata: {
      version: 1,
      author: 'Example',
      dynamicParameters: [
        { key: 'invoice_number', label: 'Invoice Number', required: true, type: 'text' },
        { key: 'invoice_date', label: 'Invoice Date', required: true, type: 'text' },
        { key: 'client_name', label: 'Client Name', required: true, type: 'text' },
        { key: 'client_email', label: 'Client Email', required: true, type: 'text' },
        { key: 'items_description', label: 'Items Description', required: true, type: 'text' },
        { key: 'items_quantity', label: 'Items Quantity', required: true, type: 'text' },
        { key: 'items_price', label: 'Items Price', required: true, type: 'text' },
        { key: 'total_amount', label: 'Total Amount', required: true, type: 'text' },
      ],
    },
  };

  try {
    // 1. Registrar la plantilla
    console.log('📝 Registering template...');
    const registrationResult = docugen.registerTemplate(invoiceTemplate, 'invoice_basic');
    console.log(`✅ Template registered: ${registrationResult.id}`);
    console.log(`   Name: ${registrationResult.name}`);
    console.log(`   Elements: ${registrationResult.elementCount}\n`);

    // 2. Obtener información de la plantilla
    console.log('📋 Template Parameters:');
    const parameters = docugen.getTemplateParameters('invoice_basic');
    parameters.forEach((param) => {
      console.log(`   - ${param.key}: ${param.label} (${param.required ? 'required' : 'optional'})`);
    });
    console.log('');

    // 3. Preparar datos de ejemplo
    const invoiceData = {
      invoice_number: 'INV-2026-001',
      invoice_date: '2026-08-18',
      client_name: 'Acme Corporation',
      client_email: 'billing@acme.com',
      items_description: 'Professional Services',
      items_quantity: '1',
      items_price: '1500.00',
      total_amount: '1500.00',
    };

    // 4. Validar datos
    console.log('🔍 Validating data...');
    const validation = docugen.validateData('invoice_basic', invoiceData);
    if (validation.valid) {
      console.log('✅ Data is valid!\n');
    } else {
      console.log('❌ Data validation failed:');
      validation.errors.forEach((error) => console.log(`   - ${error}`));
      return;
    }

    // 5. Generar PDF
    console.log('⚙️  Generating PDF...');
    const pdfBuffer = await docugen.generatePDF({
      template: 'invoice_basic',
      data: invoiceData,
    });
    console.log(`✅ PDF generated! Size: ${(pdfBuffer.length / 1024).toFixed(2)} KB\n`);

    // 6. Guardar PDF a disco
    const outputPath = './invoice_example.pdf';
    await fs.writeFile(outputPath, pdfBuffer);
    console.log(`📄 PDF saved to: ${outputPath}\n`);

    // 7. Mostrar información de la librería
    console.log('ℹ️  Library Info:');
    const info = docugen.getInfo();
    console.log(`   Version: ${info.version}`);
    console.log(`   Name: ${info.name}`);
    console.log(`   Templates registered: ${info.templates}\n`);

    console.log('✨ Example completed successfully!');
  } catch (error) {
    console.error('❌ Error:', error.message);
    process.exit(1);
  }
}

main();
