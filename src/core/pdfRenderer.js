/**
 * Motor de renderización PDF
 * Convierte plantillas JSON en documentos PDF usando pdfkit
 * Soporta 17 tipos de elementos diferentes
 */

import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import {
  resolveFieldValue,
  resolveTemplateString,
  getElementText,
  getElementQrValue,
  getElementImageSrc,
  getTableRows,
} from '../resolvers/placeholderResolver.js';
import { readExternalResource } from '../resolvers/resourceResolver.js';
import { DEFAULT_PAGE_DIMENSIONS, DEFAULT_PAGE_CONFIG, FONT_STYLES } from '../utils/constants.js';

/**
 * Dibuja un elemento individual en el documento PDF
 * @param {PDFDocument} doc - Documento PDF de pdfkit
 * @param {object} element - Elemento a dibujar
 * @param {object} payload - Datos dinámicos
 * @private
 */
const drawElement = async (doc, element, payload = {}) => {
  const x = Number(element.x || 0);
  const y = Number(element.y || 0);
  const width = Number(element.width || 100);
  const height = Number(element.height || 30);

  // Rectángulos
  if (element.type === 'rect') {
    doc
      .save()
      .rect(x, y, width, height)
      .fill(element.fill || '#eaf2ff')
      .strokeColor(element.stroke || '#9ec5fe')
      .lineWidth(element.strokeWidth || 1)
      .stroke()
      .restore();
    return;
  }

  // Líneas y separadores
  if (element.type === 'line' || element.type === 'separator') {
    doc
      .moveTo(x, y)
      .lineTo(x + (Number(element.width || 100) || 0), y + (Number(element.height || 0) || 0))
      .strokeColor(element.stroke || '#d1d5db')
      .lineWidth(element.strokeWidth || 1)
      .stroke();
    return;
  }

  // Checkboxes
  if (element.type === 'checkbox') {
    const checked = element.checked !== false;
    doc
      .rect(x, y, width || 18, height || 18)
      .strokeColor(element.stroke || '#1f9d55')
      .lineWidth(element.strokeWidth || 1)
      .stroke();

    if (checked) {
      doc
        .moveTo(x + 4, y + (height || 18) / 2)
        .lineTo(x + (width || 18) / 2, y + (height || 18) - 4)
        .lineTo(x + (width || 18) - 4, y + 4)
        .strokeColor('#18a957')
        .lineWidth(2)
        .stroke();
    }

    const label = resolveTemplateString(element.text || 'Aceptado', payload);
    if (label) {
      doc
        .fontSize(element.fontSize || 12)
        .fillColor(element.color || '#111111')
        .text(label, x + (width || 18) + 8, y + 2, {
          width: Math.max(100, Number(element.width || 180) + 80),
          align: element.align || 'left',
        });
    }
    return;
  }

  // Firmas
  if (element.type === 'signature') {
    const label = resolveTemplateString(element.text || 'Firma autorizada', payload);
    doc
      .moveTo(x, y)
      .lineTo(x + width, y)
      .strokeColor(element.stroke || '#111827')
      .lineWidth(element.strokeWidth || 1)
      .stroke();
    doc
      .fontSize(element.fontSize || 12)
      .fillColor(element.color || '#111111')
      .text(label, x, y + 12, { width, align: element.align || 'left' });
    return;
  }

  // Pies de página
  if (element.type === 'footer') {
    const footerText = resolveTemplateString(
      getElementText(element, payload) || 'Generated by Docugen',
      payload
    );
    doc
      .fontSize(element.fontSize || 11)
      .fillColor(element.color || '#4b5563')
      .text(footerText, x, y, { width, align: element.align || 'center' });
    return;
  }

  // Imágenes
  if (element.type === 'image') {
    const imageSource = getElementImageSrc(element, payload);
    if (!imageSource) return;

    try {
      const imageBuffer = await readExternalResource(imageSource);
      if (imageBuffer) {
        doc.image(imageBuffer, x, y, { fit: [width, height] });
      }
    } catch (error) {
      console.warn(`Image rendering failed: ${error.message}`);
    }
    return;
  }

  // Códigos QR
  if (element.type === 'qr') {
    const qrTarget = getElementQrValue(element, payload);
    if (!qrTarget) return;

    try {
      const qrBuffer = await QRCode.toBuffer(qrTarget, {
        type: 'png',
        margin: 1,
        width: Math.max(80, Number(width || 120)),
        color: {
          dark: '#111827',
          light: '#ffffff',
        },
      });
      doc.image(qrBuffer, x, y, { fit: [width, height] });
    } catch (error) {
      console.warn(`QR code generation failed: ${error.message}`);
    }
    return;
  }

  // Tablas
  if (element.type === 'table') {
    const rows = getTableRows(element, payload);
    if (!rows.length) return;

    const lineHeight = 18;
    const colCount = Math.max(1, ...rows.map((row) => row.length));
    const cellWidth = width / colCount;

    doc
      .rect(x, y, width, height)
      .strokeColor(element.stroke || '#cbd5e1')
      .lineWidth(element.strokeWidth || 1)
      .stroke();

    rows.forEach((row, rowIndex) => {
      row.forEach((cell, colIndex) => {
        doc
          .fontSize(element.fontSize || 10)
          .fillColor(element.color || '#111111')
          .text(String(cell || '').trim(), x + colIndex * cellWidth + 4, y + rowIndex * lineHeight + 4, {
            width: cellWidth - 8,
            height: lineHeight,
            align: element.align || 'left',
          });
      });
    });
    return;
  }

  // Obtener texto del elemento
  const textValue = getElementText(element, payload);

  // Títulos
  if (element.type === 'title') {
    doc
      .fontSize(element.fontSize || 24)
      .fillColor(element.color || '#111111')
      .font(FONT_STYLES.BOLD)
      .text(String(textValue), x, y, {
        width,
        height,
        align: element.align || 'left',
        continued: false,
      });
    return;
  }

  // Subtítulos
  if (element.type === 'subtitle') {
    doc
      .fontSize(element.fontSize || 20)
      .fillColor(element.color || '#111111')
      .font(FONT_STYLES.BOLD)
      .text(String(textValue), x, y, {
        width,
        height,
        align: element.align || 'left',
        continued: false,
      });
    return;
  }

  // Párrafos
  if (element.type === 'paragraph') {
    doc
      .fontSize(element.fontSize || 14)
      .fillColor(element.color || '#111111')
      .font(FONT_STYLES.NORMAL)
      .text(String(textValue), x, y, {
        width,
        height,
        align: element.align || 'left',
        continued: false,
      });
    return;
  }

  // Listas
  if (element.type === 'list') {
    const items = String(textValue || '')
      .split('\n')
      .map((item) => item.trim())
      .filter(Boolean)
      .map((item) => `• ${item}`);

    if (!items.length) return;

    doc
      .fontSize(element.fontSize || 14)
      .fillColor(element.color || '#111111')
      .font(FONT_STYLES.NORMAL)
      .list(items, { x, y, indent: 12, bulletIndent: 12, width, align: element.align || 'left' });
    return;
  }

  // Fechas
  if (element.type === 'date') {
    doc
      .fontSize(element.fontSize || 12)
      .fillColor(element.color || '#111111')
      .font(FONT_STYLES.BOLD)
      .text(String(textValue || new Date().toLocaleDateString('es-ES')), x, y, {
        width,
        align: element.align || 'left',
      });
    return;
  }

  // Números de página
  if (element.type === 'pageNumber') {
    const label = resolveTemplateString(element.text || 'Page {{page_number}}', payload);
    doc
      .fontSize(element.fontSize || 10)
      .fillColor(element.color || '#374151')
      .font(FONT_STYLES.NORMAL)
      .text(String(label), x, y, { width, align: element.align || 'right' });
    return;
  }

  // Texto genérico (fallback)
  doc
    .fontSize(element.fontSize || 16)
    .fillColor(element.color || '#111111')
    .font(FONT_STYLES.NORMAL)
    .text(String(textValue), x, y, {
      width,
      height,
      align: element.align || 'left',
      continued: false,
    });
};

/**
 * Genera un Buffer PDF a partir de una plantilla
 * Esta es la función principal de renderización
 *
 * @param {object} options - Opciones de generación
 * @param {object} options.template - Plantilla JSON (requerida)
 * @param {object} options.data - Datos dinámicos (default: {})
 * @returns {Promise<Buffer>} - Buffer del PDF generado
 * @throws {Error} - Si la plantilla o los parámetros son inválidos
 *
 * @example
 * const pdfBuffer = await generatePdfBuffer({
 *   template: templateObject,
 *   data: { nombre: 'Juan', total: 1500 }
 * });
 * fs.writeFileSync('documento.pdf', pdfBuffer);
 */
export const generatePdfBuffer = async ({ template, data = {} } = {}) => {
  if (!template || typeof template !== 'object') {
    throw new Error('Template is required and must be an object');
  }

  if (typeof data !== 'object' || data === null) {
    throw new Error('Data must be an object');
  }

  const pageWidth = Number(template?.dimensions?.width || DEFAULT_PAGE_DIMENSIONS.width);
  const pageHeight = Number(template?.dimensions?.height || DEFAULT_PAGE_DIMENSIONS.height);
  const pageConfig = { ...DEFAULT_PAGE_CONFIG, ...(template?.page || {}) };
  const margin = pageConfig.margin || { top: 40, right: 40, bottom: 40, left: 40 };

  return new Promise((resolve, reject) => {
    const chunks = [];

    const document = new PDFDocument({
      size: [pageWidth, pageHeight],
      margins: {
        top: margin.top || 0,
        left: margin.left || 0,
        bottom: margin.bottom || 0,
        right: margin.right || 0,
      },
      layout: 'portrait',
      bufferPages: true,
    });

    document.on('data', (chunk) => chunks.push(chunk));
    document.on('end', () => resolve(Buffer.concat(chunks)));
    document.on('error', reject);

    // Fondo blanco por defecto
    document.fillColor('#ffffff').rect(0, 0, pageWidth, pageHeight).fill();

    // Color de fondo de página si está configurado
    if (pageConfig.backgroundColor) {
      document.fillColor(pageConfig.backgroundColor).rect(0, 0, pageWidth, pageHeight).fill();
    }

    // Renderizar elementos de forma asincrónica
    (async () => {
      try {
        for (const element of template?.elements || []) {
          await drawElement(document, element, data);
        }
        document.end();
      } catch (error) {
        document.destroy();
        reject(error);
      }
    })();
  });
};

/**
 * Genera PDF y retorna metadatos junto al buffer
 *
 * @param {object} options - Opciones de generación
 * @param {object} options.template - Plantilla JSON (requerida)
 * @param {object} options.data - Datos dinámicos (default: {})
 * @returns {Promise<object>} - { buffer: Buffer, metadata: object }
 *
 * @example
 * const result = await generatePdf({
 *   template: templateObject,
 *   data: { nombre: 'Juan' }
 * });
 * console.log(result.metadata.generatedAt); // ISO timestamp
 * fs.writeFileSync('documento.pdf', result.buffer);
 */
export const generatePdf = async ({ template, data = {} } = {}) => {
  const buffer = await generatePdfBuffer({ template, data });

  return {
    buffer,
    metadata: {
      templateName: template?.name || 'Untitled',
      generatedAt: new Date().toISOString(),
      dataKeys: Object.keys(data),
      elementCount: (template?.elements || []).length,
    },
  };
};
